// Generate src/icons.ts from @iconify-json/mdi, the same icon set the apps use
// through UnoCSS presetIcons (i-mdi-*). The libraries embed plain SVG paths so
// they stay dependency-free and work in Shadow DOM and native renderers.
//
//   pnpm -C packages/core run gen:icons
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { acIconSources } from './icon-sources.mjs'

const require = createRequire(import.meta.url)
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/mdi/icons.json'), 'utf8'))

const lines = Object.entries(acIconSources).map(([name, icon]) => {
  const body = set.icons[icon]?.body
  const d = body?.match(/<path[^>]*\sd="([^"]+)"/)?.[1]
  if (!d)
    throw new Error(`mdi:${icon} is missing or not a single path`)
  return `  /** mdi:${icon} */\n  ${name}: '${d}',`
})

writeFileSync(new URL('../src/icons.ts', import.meta.url), `// Generated by scripts/gen-icons.mjs from @iconify-json/mdi. Do not edit by hand.
// Material Design Icons, Apache-2.0: https://pictogrammers.com/library/mdi/

/**
 * 遥控器按钮与提示图标（24 × 24 viewBox 的 SVG path），全部来自 Material Design
 * Icons，和站点通过 UnoCSS presetIcons 使用的 i-mdi-* 是同一套。
 */
export const acIconPaths = {
${lines.join('\n')}
} as const
`)
console.log(`wrote ${lines.length} icons to src/icons.ts`)
