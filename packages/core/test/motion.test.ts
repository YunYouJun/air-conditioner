import { readFileSync } from 'node:fs'
import { afterEach, describe, expect, it, vi } from 'vitest'
import {
  acMotion,
  acReducedMotionDuration,
  prefersReducedMotion,
  renderAcMotionCssVars,
} from '../src'

const startMarker = '/* @ac-motion-tokens:start (generated by renderAcMotionCssVars, keep in sync) */'
const endMarker = '/* @ac-motion-tokens:end */'

function readTokenBlock(relativePath: string) {
  const css = readFileSync(new URL(relativePath, import.meta.url), 'utf8')
  const start = css.indexOf(startMarker)
  const end = css.indexOf(endMarker)
  expect(start, `${relativePath} is missing the motion token block`).toBeGreaterThan(-1)
  expect(end).toBeGreaterThan(start)
  return css.slice(start + startMarker.length, end).trim()
}

describe('motion tokens', () => {
  afterEach(() => {
    vi.unstubAllGlobals()
  })

  it('renders every duration and easing as a CSS variable', () => {
    const css = renderAcMotionCssVars(':host')

    expect(css.startsWith(':host {')).toBe(true)
    for (const [key, value] of Object.entries(acMotion.duration))
      expect(css).toContain(`--acw-motion-duration-${key}: ${value}ms;`)
    for (const [key, value] of Object.entries(acMotion.easing))
      expect(css).toContain(`--acw-motion-ease-${key}: ${value};`)
    expect(css).toContain('@media (prefers-reduced-motion: reduce)')
  })

  it('never makes reduced durations longer than the defaults', () => {
    for (const [key, value] of Object.entries(acReducedMotionDuration))
      expect(value).toBeLessThanOrEqual(acMotion.duration[key as keyof typeof acMotion.duration])
  })

  it('detects prefers-reduced-motion safely', () => {
    expect(prefersReducedMotion()).toBe(false)

    vi.stubGlobal('matchMedia', (query: string) => ({ matches: query.includes('reduce') }))
    expect(prefersReducedMotion()).toBe(true)
  })

  it.each([
    ['vue', '../../vue/src/style.css'],
    ['react component library', '../../react/src/lib/style.css'],
  ])('keeps the %s stylesheet in sync with the core tokens', (_name, relativePath) => {
    expect(readTokenBlock(relativePath)).toBe(renderAcMotionCssVars(':root'))
  })
})
